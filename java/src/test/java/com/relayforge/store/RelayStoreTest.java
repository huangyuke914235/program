package com.relayforge.store;

import static org.junit.jupiter.api.Assertions.*;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.relayforge.store.Models.*;
import java.nio.file.Path;
import java.util.List;
import java.util.concurrent.CountDownLatch;
import java.util.concurrent.Executors;
import java.util.concurrent.TimeUnit;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.sqlite.SQLiteDataSource;

class RelayStoreTest {
    @TempDir Path temp;
    private RelayStore store;
    private SQLiteDataSource source;
    private final ObjectMapper mapper = new ObjectMapper();

    @BeforeEach void setup() {
        source = new SQLiteDataSource();
        source.setUrl("jdbc:sqlite:" + temp.resolve("relay.sqlite"));
        store = new RelayStore(source, mapper);
    }

    @Test void atomicAcceptanceAndIdempotency() throws Exception {
        CreatedEndpoint endpoint = store.createEndpoint("orders", "https://example.com/hook");
        var first = store.submitEvent("order.created", mapper.readTree("{\"b\":2,\"a\":1}"), List.of(endpoint.id()), "key-1");
        var duplicate = store.submitEvent("order.created", mapper.readTree("{\"a\":1,\"b\":2}"), List.of(endpoint.id()), "key-1");
        assertFalse(first.duplicate());
        assertTrue(duplicate.duplicate());
        assertEquals(first.event().id(), duplicate.event().id());
        assertEquals(1, store.listDeliveries(null, null, 50, 0).total());
        DomainException conflict = assertThrows(DomainException.class, () -> store.submitEvent("order.created", mapper.readTree("{\"a\":3}"), List.of(endpoint.id()), "key-1"));
        assertEquals("IDEMPOTENCY_CONFLICT", conflict.code());
        assertThrows(DomainException.class, () -> store.submitEvent("order.created", mapper.createObjectNode(), List.of("missing"), "key-2"));
        assertEquals(1, store.listEvents().size());
        assertTrue(store.listEndpoints().stream().noneMatch(e -> e.toString().contains(endpoint.secret())));
    }

    @Test void persistenceAndLeaseFencingProtectAgainstStaleWorkers() {
        CreatedEndpoint endpoint = store.createEndpoint("orders", "https://example.com/hook");
        var event = store.submitEvent("order.created", mapper.createObjectNode(), List.of(endpoint.id()), "key-1");
        RelayStore second = new RelayStore(source, mapper);
        long start = System.currentTimeMillis() + 5;
        Claim original = store.claimDelivery(start, 1000);
        assertNotNull(original);
        assertNull(second.claimDelivery(start + 999, 1000));
        Claim recovered = second.claimDelivery(start + 1000, 1000);
        assertNotNull(recovered);
        assertNotEquals(original.token(), recovered.token());
        assertFalse(store.completeDelivery(original, new Outcome(start + 1001, 200, "ok", null, true, false, 0)));
        assertTrue(second.completeDelivery(recovered, new Outcome(start + 1001, 200, "ok", null, true, false, 0)));
        Detail detail = store.getDelivery(event.deliveries().get(0).id());
        assertEquals("delivered", detail.delivery().status());
        assertEquals(2, detail.attempts().size());
        assertEquals(endpoint.secret(), second.getEndpointSecret(endpoint.id()));
    }

    @Test void readsExistingNodeSchemaAndReusesExistingIdempotencyFingerprint() throws Exception {
        // Hash generated by the original TypeScript canonical JSON implementation.
        String oldHash = "61c0978fdb95907f5777a2505d9fb5a298c3a37b2253ddf4e8d1c67c69ef8cde";
        CreatedEndpoint endpoint = store.createEndpoint("existing", "https://example.com/hook");
        String createdAt = "2026-10-29T10:15:30.000Z";
        try (var c = source.getConnection(); var event = c.prepareStatement("INSERT INTO events(id,type,payload,idempotencyKey,requestHash,createdAt) VALUES(?,?,?,?,?,?)");
             var delivery = c.prepareStatement("INSERT INTO deliveries(id,eventId,endpointId,endpointUrl,status,attempts,maxAttempts,nextAttemptAt,createdAt,updatedAt) VALUES(?,?,?,?,'pending',0,5,?,?,?)")) {
            event.setString(1,"evt_old"); event.setString(2,"order.created"); event.setString(3,"{\"a\":1,\"b\":2}");
            event.setString(4,"old-key"); event.setString(5,oldHash); event.setString(6,createdAt); event.executeUpdate();
            delivery.setString(1,"dlv_old"); delivery.setString(2,"evt_old"); delivery.setString(3,endpoint.id());
            delivery.setString(4,endpoint.url()); delivery.setString(5,createdAt); delivery.setString(6,createdAt); delivery.setString(7,createdAt); delivery.executeUpdate();
        }
        RelayStore migrated = new RelayStore(source, mapper);
        SubmitResult result = migrated.submitEvent("order.created", mapper.readTree("{\"b\":2,\"a\":1}"), null, "old-key");
        assertTrue(result.duplicate());
        assertEquals("evt_old", result.event().id());
        assertEquals("dlv_old", result.deliveries().get(0).id());
    }

    @Test void fingerprintMatchesNodeForNumericBoundariesAndEscapes() throws Exception {
        store.createEndpoint("orders", "https://example.com/hook");
        var payload = mapper.readTree("{\"integer\":1.0,\"negzero\":-0.0,\"small\":1e-7,\"boundary\":1e-6,\"large\":1e21,\"huge\":1e23,\"control\":\"\\u001f\"}");
        store.submitEvent("test", payload, null, "float-key");
        try (var c = source.getConnection(); var statement = c.prepareStatement("SELECT requestHash FROM events WHERE idempotencyKey=?")) {
            statement.setString(1, "float-key");
            try (var result = statement.executeQuery()) {
                assertTrue(result.next());
                assertEquals("8b6293d8ce41e94e75014d214f19b5bc683353a48671c087c6726539a67d6bd0", result.getString(1));
            }
        }
    }

    @Test void independentConnectionsCannotClaimSameJob() throws Exception {
        CreatedEndpoint endpoint = store.createEndpoint("orders", "https://example.com/hook");
        store.submitEvent("test", mapper.createObjectNode(), List.of(endpoint.id()), "key-1");
        RelayStore second = new RelayStore(source, mapper);
        CountDownLatch gate = new CountDownLatch(1);
        var executor = Executors.newFixedThreadPool(2);
        try {
            long now = System.currentTimeMillis() + 10;
            var one = executor.submit(() -> { gate.await(); return store.claimDelivery(now, 30000); });
            var two = executor.submit(() -> { gate.await(); return second.claimDelivery(now, 30000); });
            gate.countDown();
            int claims = (one.get(10, TimeUnit.SECONDS) == null ? 0 : 1) + (two.get(10, TimeUnit.SECONDS) == null ? 0 : 1);
            assertEquals(1, claims);
        } finally { executor.shutdownNow(); }
    }

    @Test void pausedEndpointAndReplayKeepAttemptHistory() {
        CreatedEndpoint endpoint = store.createEndpoint("orders", "https://example.com/hook");
        var accepted = store.submitEvent("test", mapper.createObjectNode(), List.of(endpoint.id()), "key-1");
        store.setEndpointEnabled(endpoint.id(), false);
        long now = System.currentTimeMillis() + 10;
        assertNull(store.claimDelivery(now, 30000));
        store.setEndpointEnabled(endpoint.id(), true);
        Claim first = store.claimDelivery(now, 30000);
        assertTrue(store.completeDelivery(first, new Outcome(now + 1, 400, "bad", "HTTP 400", false, false, 0)));
        assertEquals("dead", store.getDelivery(first.delivery().id()).delivery().status());
        store.retryDelivery(first.delivery().id());
        Claim replay = store.claimDelivery(System.currentTimeMillis() + 50, 30000);
        assertNotNull(replay);
        assertEquals(1, replay.delivery().attempts());
        assertEquals(2, store.getDelivery(accepted.deliveries().get(0).id()).attempts().get(0).number());
        assertEquals(24, store.stats().activity().size());
    }
}
